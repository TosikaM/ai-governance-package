def handle_request(req: dict) -> dict:
    req_id = req.get("id")
    method = req.get("method")

    # 1. Initialize
    if method == "initialize":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "protocolVersion": PROTOCOL_VERSION,
                "capabilities": {
                    "tools": {},
                    "resources": {},
                    "prompts": {}
                },
                "serverInfo": {
                    "name": SERVER_NAME,
                    "version": SERVER_VERSION
                }
            }
        }

    # 2. Initialized Notification
    elif method == "notifications/initialized":
        return {}

    # 3. Ping
    elif method == "ping":
        return {"jsonrpc": "2.0", "id": req_id, "result": {}}

    # 4. Tools List
    elif method == "tools/list":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "tools": TOOLS
            }
        }

    # 5. Tools Call
    elif method == "tools/call":
        params = req.get("params", {})
        tool_name = params.get("name")
        arguments = params.get("arguments", {})

        try:
            with contextlib.redirect_stdout(sys.stderr):
                if tool_name == "ai_governance_inspect":
                    target_dir = arguments.get("target_dir", ".")
                    res = handle_inspect(target_dir)

                elif tool_name == "ai_governance_auto_setup":
                    target_dir = arguments.get("target_dir", ".")
                    res = handle_auto_setup(target_dir)

                elif tool_name == "ai_governance_audit":
                    target_dir = arguments.get("target_dir", ".")
                    generate_html = arguments.get("generate_html", True)
                    output_filename = arguments.get("output_filename", "governance-compliance-report.html")
                    res = handle_audit(target_dir, generate_html, output_filename)

                elif tool_name == "ai_governance_check_pr":
                    target_dir = arguments.get("target_dir", ".")
                    res = handle_check_pr(target_dir)

                elif tool_name == "ai_governance_resolve":
                    manifest_path = arguments.get("manifest_path")
                    output_path = arguments.get("output_path")
                    res = handle_resolve(manifest_path, output_path)

                elif tool_name == "ai_governance_list_policies":
                    policy_id = arguments.get("policy_id")
                    res = handle_list_policies(policy_id)

                elif tool_name == "ai_governance_explain_control":
                    control_id = arguments.get("control_id")
                    res = handle_explain_control(control_id)

                else:
                    return {
                        "jsonrpc": "2.0",
                        "id": req_id,
                        "error": {"code": -32601, "message": f"Tool '{tool_name}' not found"}
                    }

            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "content": [
                        {
                            "type": "text",
                            "text": json.dumps(res, indent=2) if isinstance(res, dict) else str(res)
                        }
                    ],
                    "isError": (res.get("status") == "error") if isinstance(res, dict) else False
                }
            }

        except Exception as e:
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "content": [{"type": "text", "text": f"Error executing {tool_name}: {str(e)}"}],
                    "isError": True
                }
            }

    # 6. Resources List
    elif method == "resources/list":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "resources": RESOURCES
            }
        }

    # 7. Resources Read
    elif method == "resources/read":
        params = req.get("params", {})
        uri = params.get("uri", "")
        if uri == "governance://policies":
            res = handle_list_policies()
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "contents": [{
                        "uri": uri,
                        "mimeType": "application/json",
                        "text": json.dumps(res, indent=2)
                    }]
                }
            }
        elif uri == "governance://controls":
            c_dir = REPO_ROOT / "baseline" / "controls"
            c_list = [f.name for f in c_dir.rglob("*.yaml")]
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "contents": [{
                        "uri": uri,
                        "mimeType": "application/json",
                        "text": json.dumps({"total_controls": len(c_list), "controls": sorted(c_list)}, indent=2)
                    }]
                }
            }
        elif uri.startswith("governance://policy/"):
            pid = uri.split("/")[-1]
            res = handle_list_policies(pid)
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "contents": [{
                        "uri": uri,
                        "mimeType": "text/markdown",
                        "text": res.get("content", f"Policy {pid} not found")
                    }]
                }
            }
        else:
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "error": {"code": -32602, "message": f"Unknown resource URI: {uri}"}
            }

    # 8. Prompts List
    elif method == "prompts/list":
        return {
            "jsonrpc": "2.0",
            "id": req_id,
            "result": {
                "prompts": PROMPTS
            }
        }

    # 9. Prompts Get
    elif method == "prompts/get":
        params = req.get("params", {})
        pname = params.get("name")
        args = params.get("arguments", {})
        tdir = args.get("target_dir", ".")

        if pname == "audit_ai_repository":
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "description": "Audit an AI repository",
                    "messages": [
                        {
                            "role": "user",
                            "content": {
                                "type": "text",
                                "text": f"Please perform an AI governance audit on the repository at '{tdir}'. Run ai_governance_audit, report any failed checks or compliance gaps, and guide me on how to remediate them."
                            }
                        }
                    ]
                }
            }
        elif pname == "onboard_ai_project":
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "result": {
                    "description": "Onboard an AI project",
                    "messages": [
                        {
                            "role": "user",
                            "content": {
                                "type": "text",
                                "text": f"Please onboard the project at '{tdir}' using ai_governance_auto_setup. Inspect its architecture, generate its manifest and lifecycle cards, install the pre-commit and PR CI/CD gates, and summarize what was accomplished."
                            }
                        }
                    ]
                }
            }
        else:
            return {
                "jsonrpc": "2.0",
                "id": req_id,
                "error": {"code": -32602, "message": f"Unknown prompt: {pname}"}
            }

    # Unhandled method
    return {
        "jsonrpc": "2.0",
        "id": req_id,
        "error": {"code": -32601, "message": f"Method '{method}' not implemented"}
    }


