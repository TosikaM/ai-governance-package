def handle_audit(target_dir: str, generate_html: bool, output_filename: str) -> dict:
    agent = GovernanceAgent(target_dir=target_dir)
    audit_results = agent.audit(generate_html=generate_html, output_filename=output_filename)
    checks = audit_results.get("checks", [])
    passed = sum(1 for c in checks if c["status"] == "PASS")
    failed = sum(1 for c in checks if c["status"] == "FAIL")
    warn = sum(1 for c in checks if c["status"] == "WARN")
    
    html_report_path = str(agent.target_dir / output_filename) if generate_html else None

    return {
        "status": "success",
        "project_name": audit_results.get("project_name"),
        "project_id": audit_results.get("project_id"),
        "risk_tier": audit_results.get("risk_tier"),
        "archetype": audit_results.get("archetype"),
        "snapshot_hash": audit_results.get("snapshot_hash"),
        "compliance_summary": {
            "total_checks": len(checks),
            "passed": passed,
            "failed": failed,
            "warnings": warn,
            "overall_status": "BLOCKED" if failed > 0 else ("ACTION_REQUIRED" if warn > 0 else "COMPLIANT")
        },
        "checks": checks,
        "html_report_path": html_report_path
    }


def handle_check_pr(target_dir: str) -> dict:
    p = Path(target_dir).resolve()
    source_exts = {".py", ".ts", ".js", ".mjs", ".go", ".java", ".cpp", ".cs", ".sql"}
    
    copyleft_violations = []
    ai_generated_files = []
    secret_violations = []

    secret_regexes = [
        ("OpenAI Secret Key", re.compile(r"sk-[a-zA-Z0-9_\-]{20,}")),
        ("Anthropic API Key", re.compile(r"sk-ant-[a-zA-Z0-9_\-]{20,}")),
        ("HuggingFace Token", re.compile(r"hf_[a-zA-Z0-9]{20,}")),
        ("Generic API Key", re.compile(r"(?i)(api_key|secret_key|access_token)\s*=\s*['\"][a-zA-Z0-9_\-]{20,}['\"]"))
    ]

    for root, dirs, files in os.walk(p):
        dirs[:] = [d for d in dirs if not d.startswith(".") and d not in ["__pycache__", "node_modules", "venv", "env"]]
        for f in files:
            ext = os.path.splitext(f)[1]
            if ext in source_exts:
                fpath = os.path.join(root, f)
                rel_path = os.path.relpath(fpath, p)
                try:
                    with open(fpath, "r", encoding="utf-8", errors="ignore") as file_obj:
                        lines = file_obj.readlines()
                    content = "".join(lines)

                    for pat in COPYLEFT_PATTERNS:
                        if pat.search(content):
                            copyleft_violations.append({
                                "file": rel_path,
                                "violation": "Copyleft license marker detected (ORG-CTL-IPR-003)",
                                "license_match": pat.pattern
                            })
                            break

                    for marker in AI_MARKERS:
                        if marker.search(content):
                            ai_generated_files.append(rel_path)
                            break

                    for line_idx, line in enumerate(lines, 1):
                        if line.strip().startswith("#"):
                            continue
                        for s_name, s_pat in secret_regexes:
                            if s_pat.search(line):
                                secret_violations.append({
                                    "file": rel_path,
                                    "line": line_idx,
                                    "secret_type": s_name
                                })
                                break
                except Exception:
                    continue

    pr_blocked = (len(copyleft_violations) > 0 or len(secret_violations) > 0)
    
    return {
        "status": "success",
        "pr_gate_result": "BLOCKED" if pr_blocked else "PASSED",
        "copyleft_violations_count": len(copyleft_violations),
        "copyleft_violations": copyleft_violations,
        "secret_violations_count": len(secret_violations),
        "secret_violations": secret_violations,
        "ai_generated_files_count": len(ai_generated_files),
        "ai_generated_files": ai_generated_files,
        "enforcement_message": (
            "PR BLOCKED: Copyleft license contamination or hardcoded credentials detected. Merge locked."
            if pr_blocked else
            "PR PASSED: Code is clean of copyleft licenses and hardcoded credentials."
        )
    }


def handle_resolve(manifest_path: str, output_path: Optional[str] = None) -> dict:
    mp = Path(manifest_path).resolve()
    if not mp.exists():
        return {"status": "error", "message": f"Manifest file not found: {manifest_path}"}
    
    op = Path(output_path).resolve() if output_path else mp.parent / "effective-policy-snapshot.json"
    
    resolver_bin = REPO_ROOT / "project-kit" / "resolver" / "resolve.py"
    baseline_dir = REPO_ROOT / "baseline" / "controls"
    overlays_dir = REPO_ROOT / "overlays"

    import subprocess
    cmd = [
        sys.executable, str(resolver_bin),
        "--manifest", str(mp),
        "--baseline-dir", str(baseline_dir),
        "--overlays-dir", str(overlays_dir),
        "--output", str(op)
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        return {"status": "error", "message": f"Resolver failed: {res.stderr}"}
    
    with open(op, "r", encoding="utf-8") as f:
        sdata = json.load(f)

    return {
        "status": "success",
        "snapshot_path": str(op),
        "total_active_controls": sdata.get("total_active_controls"),
        "snapshot_integrity_hash": sdata.get("snapshot_integrity_hash"),
        "project_name": sdata.get("project_name"),
        "risk_tier": sdata.get("risk_tier"),
        "archetype": sdata.get("archetype")
    }


def handle_list_policies(policy_id: Optional[str] = None) -> dict:
    policies_dir = REPO_ROOT / "baseline" / "policies"
    if not policies_dir.exists():
        return {"status": "error", "message": "Policies directory not found"}

    if policy_id:
        clean_id = policy_id.upper().strip()
        matched = list(policies_dir.glob(f"*{clean_id}*.md"))
        if not matched:
            return {"status": "error", "message": f"Policy '{policy_id}' not found"}
        with open(matched[0], "r", encoding="utf-8") as f:
            content = f.read()
        return {
            "status": "success",
            "policy_id": clean_id,
            "filename": matched[0].name,
            "content": content
        }

    catalog = []
    for pf in sorted(policies_dir.glob("*.md")):
        with open(pf, "r", encoding="utf-8") as f:
            first_lines = [f.readline() for _ in range(10)]
        title = "Enterprise Policy"
        for line in first_lines:
            if line.startswith("# "):
                title = line.strip("# \n")
                break
        code = pf.stem.split("-")[1] if "-" in pf.stem else pf.stem
        catalog.append({
            "code": f"POL-{code}",
            "filename": pf.name,
            "title": title
        })

    return {
        "status": "success",
        "total_policies": len(catalog),
        "policies": catalog
    }


def handle_explain_control(control_id: str) -> dict:
    cid = control_id.upper().strip()
    # Normalize ID
    short_cid = cid.replace("ORG-", "")
    
    controls_dir = REPO_ROOT / "baseline" / "controls"
    found_file = None
    for yf in controls_dir.rglob("*.yaml"):
        if short_cid in yf.name.upper() or cid in yf.name.upper():
            found_file = yf
            break

    if not found_file:
        return {"status": "error", "message": f"Control '{control_id}' not found in baseline controls."}

    try:
        with open(found_file, "r", encoding="utf-8") as f:
            cdata = yaml.safe_load(f)
    except Exception as e:
        return {"status": "error", "message": f"Failed to parse control YAML: {e}"}

    remediation_tips = {
        "CTL-FAI-001": "Demographic Disparity / Bias: Ensure the disparate impact ratio across protected groups is >= 0.80. Perform sample reweighting or adversarial debiasing in training.",
        "CTL-IPR-003": "Copyleft License Contamination: AGPL/GPL code cannot be linked in commercial software. Replace with permissive MIT/Apache 2.0 libraries or clean-room reimplementation.",
        "CTL-SEC-001": "Credential Leak: Remove hardcoded API keys and secrets from source code. Migrate to environment variables (e.g., OPENAI_API_KEY) and enable git pre-commit hooks.",
        "CTL-HUM-002": "Clinician / Human Emergency Override: For high-risk decisions, ensure the UI provides an unambiguous manual override button with physician/operator sign-off before execution."
    }

    tip = remediation_tips.get(short_cid, "Ensure required lifecycle cards and configuration files are present in the repository.")

    return {
        "status": "success",
        "control_id": cdata.get("id", cid),
        "name": cdata.get("name"),
        "domain": cdata.get("domain"),
        "risk_tiers": cdata.get("applicable_risk_tiers", []),
        "objective": cdata.get("objective"),
        "normative_obligation": cdata.get("obligation", {}).get("normative_text"),
        "enforcement_point": cdata.get("enforcement", {}).get("point"),
        "remediation_guidance": tip,
        "control_file": str(found_file.relative_to(REPO_ROOT))
    }


